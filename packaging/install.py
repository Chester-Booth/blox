class LifecycleError(Exception):
    def __init__(self, code: str, message: str, data: Any = None):
        super().__init__(message)
        self.code = code
        self.message = message
        self.data = data


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(131072), b""):
            digest.update(chunk)
    return digest.hexdigest()


def product_version(source_root: Path | None = None) -> str:
    root = source_root or REPO_ROOT
    version_file = root / "VERSION"
    if version_file.is_file():
        return version_file.read_text(encoding="utf-8").strip()
    raise LifecycleError("invalid-data", "No VERSION file in the source tree.")


def _iter_source_pairs(source_root: Path) -> list[tuple[Path, str]]:
    """Return (absolute file, repo-relative posix path) for every packaged file."""
    pairs: list[tuple[Path, str]] = []
    for area in SOURCE_AREAS:
        area_root = source_root / area
        for path in sorted(area_root.rglob("*")):
            if not path.is_file() or any(part in COPY_EXCLUDE for part in path.parts):
                continue
            pairs.append((path, path.relative_to(source_root).as_posix()))
    return pairs


def _iter_data_pairs(source_root: Path) -> list[tuple[Path, str]]:
    """Return (absolute file, data-home-relative posix path) for desktop entries."""
    pairs: list[tuple[Path, str]] = []
    for area in DATA_AREAS:
        area_root = source_root / area / ".local" / "share"
        if not area_root.is_dir():
            continue
        for path in sorted(area_root.rglob("*")):
            if not path.is_file() or any(part in COPY_EXCLUDE for part in path.parts):
                continue
            pairs.append((path, path.relative_to(area_root).as_posix()))
    return pairs


@dataclass
class Action:
    kind: str  # mkdir | init-config | copy | copy-data | render-unit | link-bin | remove-owned | remove-data | remove-bin
    target: Path
    detail: str = ""

    def as_json(self) -> dict[str, str]:
        return {"kind": self.kind, "target": str(self.target), "detail": self.detail}


@dataclass
class Conflict:
    target: Path
    reason: str

    def as_json(self) -> dict[str, str]:
        return {"target": str(self.target), "reason": self.reason}


@dataclass
class Plan:
    actions: list[Action] = field(default_factory=list)
    conflicts: list[Conflict] = field(default_factory=list)
    unchanged: int = 0
    leftovers: list[Conflict] = field(default_factory=list)

    def as_json(self) -> dict[str, Any]:
        return {
            "actions": [action.as_json() for action in self.actions],
            "conflicts": [conflict.as_json() for conflict in self.conflicts],
            "unchanged": self.unchanged,
            "leftovers": [leftover.as_json() for leftover in self.leftovers],
        }


def _read_manifest(path: Path) -> dict[str, Any] | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def render_unit(template: str, roots: Roots, version: str, source_root: Path | None = None) -> str:
    root = source_root or REPO_ROOT
    text = (root / "packaging" / "units" / template).read_text(encoding="utf-8")
    for key, value in {
        "@PKG_ROOT@": str(roots.pkg_root),
        "@BIN_ROOT@": str(roots.bins),
        "@CONFIG_ROOT@": str(roots.config),
        "@VERSION@": version,
    }.items():
        text = text.replace(key, value)
    return text


def _bin_link_target(roots: Roots, name: str) -> str:
    return os.path.join("..", "share", "blox", "bin", name)


@contextlib.contextmanager
def _owned_regular_file(directory: Path, relative: str, allowed_areas: tuple[str, ...]):
    """Open a recorded file without following links outside its owner."""
    parts = relative.split("/")
    if not parts or parts[0] not in allowed_areas or any(part in {"", ".", ".."} for part in parts):
        raise OSError("invalid retired file path")
    descriptors: list[int] = []
    try:
        parent = os.open(directory, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        descriptors.append(parent)
        if os.fstat(parent).st_uid != os.getuid():
            raise OSError("directory is not owned by the current user")
        for part in parts[:-1]:
            parent = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=parent)
            descriptors.append(parent)
            if os.fstat(parent).st_uid != os.getuid():
                raise OSError("directory is not owned by the current user")
        descriptor = os.open(parts[-1], os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=parent)
        descriptors.append(descriptor)
        info = os.fstat(descriptor)
        if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid():
            raise OSError("retired file is not an owned regular file")
        digest = hashlib.sha256()
        for chunk in iter(lambda: os.read(descriptor, 131072), b""):
            digest.update(chunk)
        os.lseek(descriptor, 0, os.SEEK_SET)
        yield parent, parts[-1], descriptor, info, digest.hexdigest()
    finally:
        for descriptor in reversed(descriptors):
            os.close(descriptor)


def _owned_package_file(package: Path, relative: str):
    return _owned_regular_file(package, relative, SOURCE_AREAS + ("VERSION",))


def _retired_backup(roots: Roots, stamp: str, bucket: str, relative: str) -> Path:
    backup = roots.backups / stamp / bucket / relative
    if backup.exists() or backup.is_symlink():
        backup = roots.backups / f"{stamp}-retired-{time.time_ns()}" / bucket / relative
    backup.parent.mkdir(parents=True, exist_ok=True)
    return backup


def _remove_retired_file(roots: Roots, action: Action, stamp: str, journal: list[dict[str, Any]]) -> Path:
    """Back up and remove only an unchanged file from the previous manifest."""
    directory = roots.data.parent if action.kind == "remove-data" else roots.pkg_root
    areas = ("applications", "icons") if action.kind == "remove-data" else SOURCE_AREAS
    relative = action.target.relative_to(directory).as_posix()
    with _owned_regular_file(directory, relative, areas) as (parent, name, descriptor, info, digest):
        if digest != action.detail:
            raise LifecycleError("conflict", "A retired package file changed after planning.", str(action.target))
        backup = _retired_backup(roots, stamp, "data" if action.kind == "remove-data" else "pkg", relative)
        with os.fdopen(os.dup(descriptor), "rb") as source, backup.open("xb") as destination:
            shutil.copyfileobj(source, destination)
        os.chmod(backup, stat.S_IMODE(info.st_mode))
        os.utime(backup, ns=(info.st_atime_ns, info.st_mtime_ns))
        current = os.stat(name, dir_fd=parent, follow_symlinks=False)
        if (current.st_dev, current.st_ino, current.st_size, current.st_mtime_ns) != (info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns):
            raise LifecycleError("conflict", "A retired package file changed before removal.", str(action.target))
        with (roots.backups / "ledger.jsonl").open("a", encoding="utf-8") as handle:
            handle.write(json.dumps({"time": stamp, "original": str(action.target), "backup": str(backup), "kind": "retired-file", "sha256": digest}, sort_keys=True) + "\n")
        journal.append({"kind": action.kind, "target": str(action.target), "backup": str(backup), "created": False})
        os.unlink(name, dir_fd=parent)
        return backup


@contextlib.contextmanager
def _owned_bin_link(directory: Path, name: str):
    if not name or name in {".", ".."} or Path(name).name != name:
        raise OSError("invalid retired binary name")
    parent = os.open(directory, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        if os.fstat(parent).st_uid != os.getuid():
            raise OSError("binary directory is not owned by the current user")
        info = os.stat(name, dir_fd=parent, follow_symlinks=False)
        if not stat.S_ISLNK(info.st_mode) or info.st_uid != os.getuid():
            raise OSError("retired binary is not an owned symlink")
        yield parent, info, os.readlink(name, dir_fd=parent)
    finally:
        os.close(parent)


def _remove_retired_bin_link(roots: Roots, action: Action, stamp: str, journal: list[dict[str, Any]]) -> Path:
    name = action.target.name
    with _owned_bin_link(roots.bins, name) as (parent, info, target):
        if target != action.detail:
            raise LifecycleError("conflict", "A retired binary link changed after planning.", str(action.target))
        backup = _retired_backup(roots, stamp, "bins", name)
        os.symlink(target, backup)
        os.utime(backup, ns=(info.st_atime_ns, info.st_mtime_ns), follow_symlinks=False)
        current = os.stat(name, dir_fd=parent, follow_symlinks=False)
        if (current.st_dev, current.st_ino, current.st_mtime_ns) != (info.st_dev, info.st_ino, info.st_mtime_ns):
            raise LifecycleError("conflict", "A retired binary link changed before removal.", str(action.target))
        with (roots.backups / "ledger.jsonl").open("a", encoding="utf-8") as handle:
            handle.write(json.dumps({"time": stamp, "original": str(action.target), "backup": str(backup), "kind": "retired-symlink", "target_of_link": target, "sha256": None}, sort_keys=True) + "\n")
        journal.append({"kind": action.kind, "target": str(action.target), "backup": str(backup), "created": False})
        os.unlink(name, dir_fd=parent)
        return backup


def build_plan(roots: Roots, source_root: Path | None = None) -> Plan:
    """Predict every effect of an install without touching the target."""
    root = source_root or REPO_ROOT
    plan = Plan()
    installed = _read_manifest(roots.manifest)

    for directory in (roots.pkg_root, roots.bins, roots.systemd_user):
        if not directory.is_dir():
            plan.actions.append(Action("mkdir", directory))

    module = roots.config / "hyprland-settings.lua"
    if roots.config.is_symlink() or (roots.config.exists() and not roots.config.is_dir()):
        plan.leftovers.append(Conflict(roots.config, "config directory is a personal link or file; module bootstrap skipped"))
    elif not module.exists() and not module.is_symlink():
        plan.actions.append(Action("init-config", module, "hyprland-settings.lua"))

    source_pairs = _iter_source_pairs(root)
    for source, rel in source_pairs:
        target = roots.pkg_root / rel
        if not target.exists():
            plan.actions.append(Action("copy", target, rel))
            continue
        current = sha256(target)
        source_hash = sha256(source)
        # The recorded manifest arbitrates ownership: a file that matches
        # neither the manifest nor the incoming source is foreign, even when
        # the installer runs from the installed tree itself.
        recorded = installed.get("files", {}).get(rel, {}).get("sha256") if installed else None
        # A stale manifest must not flag a target that already matches the
        # incoming source (an out-of-band sync of identical content).
        if current == source_hash:
            plan.unchanged += 1
        elif recorded is not None and recorded == current:
            plan.actions.append(Action("copy", target, rel))
        else:
            plan.conflicts.append(Conflict(target, "existing file is not owned by the recorded manifest"))
            # Planned as well so --force backs the foreign file up and replaces it.
            plan.actions.append(Action("copy", target, rel))

    incoming = {rel for _, rel in source_pairs} | {"VERSION"}
    for relative, record in ((installed or {}).get("files") or {}).items():
        if relative in incoming:
            continue
        target = roots.pkg_root / relative
        try:
            with _owned_package_file(roots.pkg_root, relative) as (_, _, _, _, digest):
                if isinstance(record, dict) and record.get("sha256") == digest:
                    plan.actions.append(Action("remove-owned", target, digest))
                else:
                    plan.leftovers.append(Conflict(target, "retired package file was modified; preserved"))
        except FileNotFoundError:
            pass
        except OSError as error:
            plan.leftovers.append(Conflict(target, "retired package path is not owned or safe; preserved: " + str(error)))

    data_home = roots.data.parent
    data_pairs = _iter_data_pairs(root)
    for source, rel in data_pairs:
        target = data_home / rel
        if not target.exists():
            plan.actions.append(Action("copy-data", target, rel))
            continue
        current = sha256(target)
        recorded = installed.get("data_files", {}).get(rel, {}).get("sha256") if installed else None
        if current == sha256(source):
            plan.unchanged += 1
        elif recorded is not None and recorded == current:
            plan.actions.append(Action("copy-data", target, rel))
        else:
            plan.conflicts.append(Conflict(target, "existing file is not owned by the recorded manifest"))
            plan.actions.append(Action("copy-data", target, rel))

    incoming_data = {rel for _, rel in data_pairs}
    for relative, record in ((installed or {}).get("data_files") or {}).items():
        if relative in incoming_data:
            continue
        target = data_home / relative
        try:
            with _owned_regular_file(data_home, relative, ("applications", "icons")) as (_, _, _, _, digest):
                if isinstance(record, dict) and record.get("sha256") == digest:
                    plan.actions.append(Action("remove-data", target, digest))
                else:
                    plan.leftovers.append(Conflict(target, "retired data file was modified; preserved"))
        except FileNotFoundError:
            pass
        except OSError as error:
            plan.leftovers.append(Conflict(target, "retired data path is not owned or safe; preserved: " + str(error)))

    version = product_version(root)
    for template in UNIT_TEMPLATES:
        name = template.removesuffix(".in")
        target = roots.systemd_user / name
        rendered = render_unit(template, roots, version, root)
        if target.is_symlink():
            plan.conflicts.append(Conflict(target, "existing unit is a personal symlink"))
            plan.actions.append(Action("render-unit", target, template))
        elif not target.exists():
            plan.actions.append(Action("render-unit", target, template))
        elif target.is_file() and target.read_bytes() == rendered.encode("utf-8"):
            plan.unchanged += 1
        else:
            recorded = (installed or {}).get("unit_files", {}).get(name, {}).get("sha256")
            if not target.is_file() or recorded != sha256(target):
                plan.conflicts.append(Conflict(target, "existing unit is not owned by the recorded manifest"))
            plan.actions.append(Action("render-unit", target, template))

    for name in INSTALLED_BINS:
        link = roots.bins / name
        expected = _bin_link_target(roots, name)
        if link.is_symlink() and os.readlink(link) == expected:
            plan.unchanged += 1
        elif link.is_symlink():
            plan.actions.append(Action("link-bin", link, name))
        elif link.exists():
            plan.conflicts.append(Conflict(link, "existing program is not a Blox link"))
        else:
            plan.actions.append(Action("link-bin", link, name))
    for name in (installed or {}).get("bins") or []:
        if name in INSTALLED_BINS:
            continue
        link = roots.bins / name
        expected = _bin_link_target(roots, name)
        try:
            with _owned_bin_link(roots.bins, name) as (_, _, target):
                if target == expected:
                    plan.actions.append(Action("remove-bin", link, expected))
                else:
                    plan.leftovers.append(Conflict(link, "retired binary link points elsewhere; preserved"))
        except FileNotFoundError:
            pass
        except OSError as error:
            plan.leftovers.append(Conflict(link, "retired binary path is not owned or safe; preserved: " + str(error)))
    return plan


def _backup_conflict(roots: Roots, target: Path, stamp: str) -> Path:
    if target.is_relative_to(roots.pkg_root):
        destination = roots.backups / stamp / "pkg" / target.relative_to(roots.pkg_root)
    else:
        destination = roots.backups / stamp / "misc" / hashlib.sha256(str(target).encode()).hexdigest() / target.name
    destination.parent.mkdir(parents=True, exist_ok=True)
    # Never follow symlinks: a unit symlink into a dotfiles tree must be
    # preserved as the link itself so its target stays byte-identical.
    is_link = target.is_symlink()
    shutil.copy2(target, destination, follow_symlinks=False)
    entry = {
        "time": stamp,
        "original": str(target),
        "backup": str(destination),
        "kind": "symlink" if is_link else "file",
        "target_of_link": os.readlink(target) if is_link else None,
        "sha256": None if is_link else sha256(target),
    }
    with (roots.backups / "ledger.jsonl").open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(entry, sort_keys=True) + "\n")
    return destination



def _require_external_source(roots: Roots, source_root: Path | None) -> Path:
    """Install and update need a source tree outside the installed root."""
    root = source_root or REPO_ROOT
    try:
        same = root.samefile(roots.pkg_root)
    except OSError:
        same = False
    if same:
        raise LifecycleError(
            "unavailable",
            "No source tree is available from the installed CLI. Run lifecycle install from a checkout or release artefact.",
        )
    return root


def _require_native_services(source_root: Path | None = None) -> None:
    """Reject incomplete release artefacts before creating locks or install state."""
    root = source_root or REPO_ROOT
    if not ((root / "shell/native/services").is_dir()
            or (root / "shell/services/NativeServiceAvailability.qml").is_file()):
        return
    try:
        validate_native_services(root / "shell/native/qml", root)
    except BuildError as error:
        raise LifecycleError(
            "unavailable",
            "Blox.Services is missing or stale. Run make native-services in the source tree before installing or updating.",
        ) from error


def _require_native_widgets(source_root: Path | None = None) -> None:
    """Validate the prebuilt terminal module before any lifecycle mutation."""
    root = source_root or REPO_ROOT
    if not ((root / "widgets/native").is_dir()
            or (root / "widgets/qml/Blox/Widgets/Terminal/qmldir").is_file()):
        return
    try:
        validate_native_widgets(root / "widgets/qml", root)
    except WidgetBuildError as error:
        raise LifecycleError(
            "unavailable",
            "Blox.Widgets.Terminal is missing or stale. Run make native-widgets in the source tree before installing or updating.",
        ) from error


def _append_generation(roots: Roots, from_version: str, to_version: str, result: str) -> None:
    ledger: list[dict[str, Any]] = []
    if roots.generations.is_file():
        try:
            ledger = json.loads(roots.generations.read_text(encoding="utf-8"))
        except ValueError:
            ledger = []
    ledger.append({"time": time.strftime("%Y-%m-%dT%H:%M:%S"), "from": from_version, "to": to_version, "result": result})
    roots.generations.write_text(json.dumps(ledger, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _read_generations(roots: Roots) -> bytes | None:
    try:
        return roots.generations.read_bytes()
    except OSError:
        return None


def _write_generations(roots: Roots, payload: bytes | None) -> None:
    if payload is None:
        roots.generations.unlink(missing_ok=True)
    else:
        roots.generations.write_bytes(payload)


_lifecycle_mutex = threading.RLock()
_lifecycle_local = threading.local()


def _serialised(dry_run_index: int, source_root_index: int | None = None):
    """Serialise lifecycle writers, including nested update-to-install calls."""
    def decorate(function):
        @functools.wraps(function)
        def call(roots: Roots, *args, **kwargs):
            if source_root_index is not None:
                source_root = kwargs.get("source_root", args[source_root_index] if len(args) > source_root_index else None)
                _require_native_services(source_root)
                _require_native_widgets(source_root)
            dry_run = kwargs.get("dry_run", args[dry_run_index] if len(args) > dry_run_index else False)
            if dry_run:
                return function(roots, *args, **kwargs)
            with _lifecycle_mutex:
                held = getattr(_lifecycle_local, "held", set())
                lock_path = roots.pkg_root.parent / ".blox-lifecycle.lock"
                if lock_path in held:
                    return function(roots, *args, **kwargs)
                lock_path.parent.mkdir(parents=True, exist_ok=True)
                state = os.open(lock_path.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
                try:
                    if os.fstat(state).st_uid != os.getuid():
                        raise LifecycleError("conflict", "Lifecycle lock directory belongs to another user.")
                    descriptor = os.open(lock_path.name, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600, dir_fd=state)
                finally:
                    os.close(state)
                try:
                    info = os.fstat(descriptor)
                    if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or info.st_nlink != 1:
                        raise LifecycleError("conflict", "Lifecycle lock is not an owned regular file.")
                    fcntl.flock(descriptor, fcntl.LOCK_EX)
                    _lifecycle_local.held = held | {lock_path}
                    try:
                        return function(roots, *args, **kwargs)
                    finally:
                        _lifecycle_local.held = held
                finally:
                    os.close(descriptor)
        return call
    return decorate


@_serialised(0, source_root_index=2)
def install(roots: Roots, dry_run: bool = False, force: bool = False, source_root: Path | None = None, migrate: bool = True) -> dict[str, Any]:
    """Install the product transactionally.

    Every mutation is journalled; any failure restores the exact prior
    state, including symlinked units, the manifest, migration effects and
    the generation ledger."""
    root = _require_external_source(roots, source_root)
    version = product_version(root)
    plan = build_plan(roots, root)
    report: dict[str, Any] = {"version": version, "dry_run": dry_run, "plan": plan.as_json()}
    if dry_run:
        return report
    if plan.conflicts and not force:
        raise LifecycleError(
            "conflict",
            "Existing files are not owned by Blox. Review the report, then rerun with --force to back them up.",
            {"conflicts": [conflict.as_json() for conflict in plan.conflicts]},
        )

    from migrations import read_ledger, restore_ledger_after, run_migrations

    stamp = _operation_stamp()
    ledger_before = len(read_ledger(roots))
    report_migrations = None
    journal: list[dict[str, Any]] = []
    manifest_before = roots.manifest.read_bytes() if roots.manifest.exists() else None
    generations_before = _read_generations(roots)
    config_defaults = (_read_manifest(roots.manifest) or {}).get("config_defaults", {})

    def undo_journal() -> None:
        for entry in reversed(journal):
            target = Path(entry["target"])
            backup = entry.get("backup")
            if entry["kind"] == "directory-mode":
                os.chmod(target, entry["mode"])
            elif backup is not None:
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(Path(backup), target, follow_symlinks=False)
            elif entry.get("created") and (target.is_symlink() or target.exists()):
                target.unlink()

    try:
        if migrate:
            # Relocate legacy user data inside the same transaction as the
            # package install. If any later package mutation fails, the
            # migration ledger and pre-images return the old topology.
            incoming = {rel for _, rel in _iter_source_pairs(root)}
            report_migrations = run_migrations(
                roots,
                from_version="fresh-install",
                to_version=version,
                package_rels=incoming,
            )
            plan = build_plan(roots, root)
            report["plan"] = plan.as_json()
        backed_up: list[str] = []
        for action in plan.actions:
            if action.kind == "init-config":
                if _initialise_hyprland_module(roots, journal):
                    config_defaults[action.detail] = {"sha256": hashlib.sha256(HYPRLAND_DEFAULT_MODULE).hexdigest()}
                continue
            if action.kind == "mkdir":
                action.target.mkdir(parents=True, exist_ok=True)
                continue
            if action.kind in {"remove-owned", "remove-data", "remove-bin"}:
                backup_path = _remove_retired_bin_link(roots, action, stamp, journal) if action.kind == "remove-bin" else _remove_retired_file(roots, action, stamp, journal)
                backed_up.append(str(action.target))
                continue
            action.target.parent.mkdir(parents=True, exist_ok=True)
            created = not (action.target.is_symlink() or action.target.exists())
            backup_path: Path | None = None
            if not created:
                backup_path = _backup_conflict(roots, action.target, stamp)
                backed_up.append(str(action.target))
                action.target.unlink()
            journal.append({"kind": action.kind, "target": str(action.target), "backup": str(backup_path) if backup_path else None, "created": created})

            if action.kind == "copy":
                shutil.copy2(root / action.detail, action.target, follow_symlinks=False)
                if action.detail.startswith("bin/"):
                    os.chmod(action.target, 0o755)
            elif action.kind == "copy-data":
                shutil.copy2(root / "applications" / ".local" / "share" / action.detail, action.target, follow_symlinks=False)
            elif action.kind == "render-unit":
                action.target.write_text(render_unit(action.detail, roots, version, root), encoding="utf-8")
                os.chmod(action.target, 0o644)
            elif action.kind == "link-bin":
                os.symlink(_bin_link_target(roots, action.detail), action.target)

        version_source = root / "VERSION"
        version_target = roots.pkg_root / "VERSION"
        if version_source.is_file() and not (version_target.exists() and version_source.samefile(version_target)):
            created_version = not version_target.exists()
            version_backup = None
            if not created_version:
                version_backup = _backup_conflict(roots, version_target, stamp)
                version_target.unlink()
            journal.append({
                "kind": "copy",
                "target": str(version_target),
                "backup": str(version_backup) if version_backup else None,
                "created": created_version,
            })
            shutil.copy2(version_source, version_target)

        files = {rel: {"sha256": sha256(target)} for target, rel in _iter_source_pairs(root)}
        if (roots.pkg_root / "VERSION").is_file():
            files["VERSION"] = {"sha256": sha256(roots.pkg_root / "VERSION")}
        data_home = roots.data.parent
        data_files = {rel: {"sha256": sha256(data_home / rel)} for _, rel in _iter_data_pairs(root)}
        manifest_payload = json.dumps({
            "manifest_version": 1,
            "product_version": version,
            "prefix": str(roots.prefix),
            "files": files,
            "data_files": data_files,
            "config_defaults": config_defaults,
            "units": [template.removesuffix(".in") for template in UNIT_TEMPLATES],
            "unit_files": {template.removesuffix(".in"): {"sha256": sha256(roots.systemd_user / template.removesuffix(".in"))} for template in UNIT_TEMPLATES},
            "bins": list(INSTALLED_BINS),
        }, indent=2, sort_keys=True) + "\n"
        roots.manifest.parent.mkdir(parents=True, exist_ok=True)
        roots.manifest.write_text(manifest_payload, encoding="utf-8")

        if report_migrations is not None:
            report["migrations"] = report_migrations

    except BaseException:
        undo_journal()
        restore_ledger_after(roots, ledger_before)
        if roots.manifest.exists() and manifest_before is None:
            roots.manifest.unlink()
        elif manifest_before is not None:
            roots.manifest.write_bytes(manifest_before)
        if migrate:
            _write_generations(roots, generations_before)
        raise

    if migrate:
        _append_generation(roots, "none", version, "installed")
        finalise_legacy_user_themes(roots, report.get("migrations") or [])

    report["backed_up"] = backed_up
    report["installed"] = True
    return report


def finalise_legacy_user_themes(roots: Roots, entries: list[dict[str, Any]]) -> int:
    """Delete relocated theme sources once the install has committed."""
    removed = 0
    for entry in entries:
        if entry.get("migration") != "legacy-user-themes":
            continue
        for text in entry.get("sources") or []:
            source = Path(text)
            if source.is_file():
                source.unlink()
                removed += 1
    return removed


def _initialise_hyprland_module(roots: Roots, journal: list[dict[str, Any]]) -> bool:
    """Create the harmless include target once, without editing personal config."""
    roots.config.mkdir(mode=0o700, parents=True, exist_ok=True)
    directory = os.open(roots.config, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        info = os.fstat(directory)
        if info.st_uid != os.getuid():
            raise LifecycleError("conflict", "Blox configuration directory belongs to another user.")
        try:
            descriptor = os.open("hyprland-settings.lua", os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=directory)
        except FileExistsError:
            return False
        journal.append({"kind": "init-config", "target": str(roots.config / "hyprland-settings.lua"), "backup": None, "created": True})
        with os.fdopen(descriptor, "wb") as module:
            if stat.S_IMODE(info.st_mode) != 0o700:
                journal.append({"kind": "directory-mode", "target": str(roots.config), "mode": stat.S_IMODE(info.st_mode)})
                os.fchmod(directory, 0o700)
            module.write(HYPRLAND_DEFAULT_MODULE)
            module.flush()
            os.fsync(module.fileno())
        return True
    finally:
        os.close(directory)


def _operation_stamp() -> str:
    return time.strftime("%Y%m%dT%H%M%S") + "-" + uuid.uuid4().hex


def _salvage_foreign(roots: Roots, stamp: str) -> list[str]:
    """Save unrecorded and modified package files before removing the tree."""
    installed = _read_manifest(roots.manifest) or {}
    owned = installed.get("files", {})
    salvaged: list[str] = []
    if not roots.pkg_root.is_dir() or roots.pkg_root.is_symlink():
        raise LifecycleError("conflict", "Package root is not an owned directory.")
    if roots.pkg_root.stat().st_uid != os.getuid():
        raise LifecycleError("conflict", "Package root belongs to another user.")
    for path in sorted(roots.pkg_root.rglob("*")):
        if not path.is_file() and not path.is_symlink():
            continue
        rel = path.relative_to(roots.pkg_root).as_posix()
        if rel == "manifest.json" and not path.is_symlink():
            continue
        try:
            with _owned_package_file(roots.pkg_root, rel) as (_, _, _, _, digest):
                if owned.get(rel, {}).get("sha256") == digest:
                    continue
        except OSError:
            pass
        destination = _retired_backup(roots, stamp, "pkg-leftovers", rel)
        shutil.move(str(path), str(destination))
        entry = {"time": stamp, "original": str(path), "backup": str(destination), "kind": "salvaged", "sha256": None}
        with (roots.backups / "ledger.jsonl").open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(entry, sort_keys=True) + "\n")
        salvaged.append(str(path))
    return salvaged


def _external_entries(roots: Roots, manifest: dict[str, Any], plan: Plan | None = None) -> list[tuple[str, str]]:
    entries = {( "data", rel) for rel in manifest.get("data_files", {})}
    entries.update(("unit", name) for name in manifest.get("units", []))
    entries.update(("bin", name) for name in manifest.get("bins", []))
    for action in (plan.actions if plan else []):
        if action.kind == "init-config":
            entries.add(("config", action.detail))
        elif action.kind in {"copy-data", "remove-data"}:
            entries.add(("data", action.target.relative_to(roots.data.parent).as_posix()))
        elif action.kind == "render-unit":
            entries.add(("unit", action.target.name))
        elif action.kind in {"link-bin", "remove-bin"}:
            entries.add(("bin", action.target.name))
    for group, relative in entries:
        parts = relative.split("/")
        if any(part in {"", ".", ".."} for part in parts) or (group == "data" and parts[0] not in {"applications", "icons"}) or (group != "data" and len(parts) != 1) or (group == "config" and relative != "hyprland-settings.lua"):
            raise LifecycleError("invalid-data", "Invalid external path in installed manifest.", relative)
    return sorted(entries)


def _external_root(roots: Roots, group: str) -> Path:
    return {"data": roots.data.parent, "unit": roots.systemd_user, "bin": roots.bins, "config": roots.config}[group]


@contextlib.contextmanager
def _external_parent(directory: Path, relative: str):
    """Anchor external reads and mutations in owned directories without links."""
    descriptors = []
    try:
        parent = os.open(directory, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        descriptors.append(parent)
        for part in relative.split("/")[:-1]:
            if os.fstat(parent).st_uid != os.getuid():
                raise OSError("external directory belongs to another user")
            parent = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=parent)
            descriptors.append(parent)
        if os.fstat(parent).st_uid != os.getuid():
            raise OSError("external directory belongs to another user")
        yield parent, relative.split("/")[-1]
    finally:
        for descriptor in reversed(descriptors):
            os.close(descriptor)


def _external_image(roots: Roots, group: str, relative: str, backup: Path | None = None) -> dict[str, Any]:
    try:
        with _external_parent(_external_root(roots, group), relative) as (parent, name):
            info = os.stat(name, dir_fd=parent, follow_symlinks=False)
            if info.st_uid != os.getuid():
                raise OSError("external path belongs to another user")
            if stat.S_ISLNK(info.st_mode):
                return {"kind": "link", "target": os.readlink(name, dir_fd=parent)}
            if not stat.S_ISREG(info.st_mode):
                raise OSError("external path is not a regular file or link")
            descriptor = os.open(name, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=parent)
            with os.fdopen(descriptor, "rb") as source:
                opened = os.fstat(source.fileno())
                if (opened.st_dev, opened.st_ino, opened.st_uid) != (info.st_dev, info.st_ino, os.getuid()):
                    raise OSError("external file changed while reading")
                payload = source.read()
            if backup is not None:
                backup.write_bytes(payload)
                os.chmod(backup, stat.S_IMODE(info.st_mode))
                os.utime(backup, ns=(info.st_atime_ns, info.st_mtime_ns))
            return {"kind": "file", "sha256": hashlib.sha256(payload).hexdigest(), "mode": stat.S_IMODE(info.st_mode)}
    except FileNotFoundError:
        return {"kind": "missing"}
    except OSError as error:
        raise LifecycleError("conflict", "External path is not safe to restore.", {"path": str(_external_root(roots, group) / relative), "reason": str(error)}) from error


def _snapshot_external(roots: Roots, directory: Path, entries: list[tuple[str, str]]) -> list[dict[str, Any]]:
    images = []
    for index, (group, relative) in enumerate(entries):
        backup = str(index)
        image = _external_image(roots, group, relative, directory / backup)
        images.append({"group": group, "relative": relative, "backup": backup, "before": image})
    return images


def _restore_external(roots: Roots, directory: Path, images: list[dict[str, Any]]) -> None:
    for entry in images:
        group, relative = entry["group"], entry["relative"]
        before = entry["before"]
        target = _external_root(roots, group) / relative
        if before["kind"] != "missing":
            target.parent.mkdir(parents=True, exist_ok=True)
        try:
            with _external_parent(_external_root(roots, group), relative) as (parent, name):
                try:
                    os.unlink(name, dir_fd=parent)
                except FileNotFoundError:
                    pass
                if before["kind"] == "link":
                    os.symlink(before["target"], name, dir_fd=parent)
                elif before["kind"] == "file":
                    image = directory / entry["backup"]
                    if sha256(image) != before["sha256"]:
                        raise LifecycleError("invalid-data", "External preimage is damaged.", str(image))
                    descriptor = os.open(name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, before["mode"], dir_fd=parent)
                    with os.fdopen(descriptor, "wb") as destination, image.open("rb") as source:
                        shutil.copyfileobj(source, destination)
                    os.chmod(name, before["mode"], dir_fd=parent)
                    info = image.stat()
                    os.utime(name, ns=(info.st_atime_ns, info.st_mtime_ns), dir_fd=parent)
        except FileNotFoundError:
            if before["kind"] != "missing":
                raise


@_serialised(1)
def uninstall(roots: Roots, purge: bool = False, dry_run: bool = False) -> dict[str, Any]:
    installed = _read_manifest(roots.manifest)
    if not installed:
        raise LifecycleError("unavailable", "Blox is not installed at this prefix.")

    removed: list[str] = []
    leftovers: list[str] = []
    owned_external = []
    for group, relative in _external_entries(roots, installed):
        target = _external_root(roots, group) / relative
        try:
            image = _external_image(roots, group, relative)
            if image["kind"] == "missing":
                continue
            records = installed.get("unit_files" if group == "unit" else "data_files", {})
            owned = (image["kind"] == "link" and image["target"] == _bin_link_target(roots, relative)) if group == "bin" else (image["kind"] == "file" and records.get(relative, {}).get("sha256") == image["sha256"])
            if owned:
                owned_external.append((group, relative, image))
                removed.append(str(target))
            else:
                leftovers.append(str(target))
        except LifecycleError:
            leftovers.append(str(target))
    removed.extend([str(roots.previous_pkg_root), str(roots.pkg_root)])
    if purge:
        removed.extend(str(path) for path in (roots.config, roots.data, roots.state, roots.cache))
    if dry_run:
        return {"dry_run": True, "removed": removed, "leftovers": leftovers, "purged": purge}
    salvaged = _salvage_foreign(roots, _operation_stamp())
    salvage_backup = None
    if purge and salvaged:
        # Purge mutable Blox state, but keep personal package edits outside it.
        salvage_backup = roots.state.parent / ("blox-uninstall-backups-" + uuid.uuid4().hex)
        shutil.move(str(roots.backups), str(salvage_backup))
    leftovers.extend(salvaged)
    for group, relative, expected in owned_external:
        if _external_image(roots, group, relative) != expected:
            raise LifecycleError("conflict", "An installed path changed before uninstall.", relative)
        with _external_parent(_external_root(roots, group), relative) as (parent, name):
            os.unlink(name, dir_fd=parent)
    for path in (roots.previous_pkg_root, roots.pkg_root):
        if path.is_symlink():
            leftovers.append(str(path))
        elif path.is_dir():
            shutil.rmtree(path)
    if purge:
        for path in (roots.config, roots.data, roots.state, roots.cache):
            if path.is_symlink():
                leftovers.append(str(path))
            elif path.is_dir():
                shutil.rmtree(path)
    else:
        for path in (roots.config, roots.data, roots.state):
            if path.is_dir() and any(path.iterdir()):
                leftovers.append(str(path))
    return {"dry_run": False, "removed": removed, "leftovers": leftovers, "salvaged": salvaged, "salvage_backup": str(salvage_backup) if salvage_backup else None, "purged": purge}


@_serialised(0, source_root_index=1)
def update(roots: Roots, dry_run: bool = False, source_root: Path | None = None) -> dict[str, Any]:
    from migrations import read_ledger, restore_ledger_after, run_migrations

    source_root = _require_external_source(roots, source_root)
    installed = _read_manifest(roots.manifest)
    if not installed:
        raise LifecycleError("unavailable", "Blox is not installed; run lifecycle install first.")
    version = product_version(source_root)
    current = str(installed.get("product_version"))
    if version == current:
        return {"updated": False, "version": version, "reason": "already at this version"}
    if dry_run:
        return {"updated": True, "from": current, "to": version, "dry_run": True}

    roots.state.mkdir(parents=True, exist_ok=True)
    snapshot = Path(tempfile.mkdtemp(prefix=".update-snapshot-", dir=roots.state))
    package = snapshot / "package"
    external = snapshot / "external"
    external.mkdir()
    images = []
    captured_package = False
    previous_external = roots.state / "previous-external"
    older_package = snapshot / "older-package"
    older_external = snapshot / "older-external"
    promotion_started = False
    ledger_before = len(read_ledger(roots))
    generations_before = _read_generations(roots)
    try:
        shutil.copytree(roots.pkg_root, package, symlinks=True)
        captured_package = True
        images = _snapshot_external(roots, external, _external_entries(roots, installed, build_plan(roots, source_root)))
        (external / "manifest.json").write_text(json.dumps({"images": images}, sort_keys=True), encoding="utf-8")
        result = install(roots, source_root=source_root, migrate=False)
        result["migrations"] = run_migrations(
            roots, from_version=current, to_version=version,
            package_rels={rel for _, rel in _iter_source_pairs(source_root)},
        )
        for entry in images:
            entry["after"] = _external_image(roots, entry["group"], entry["relative"])
        (external / "manifest.json").write_text(json.dumps({"images": images}, sort_keys=True), encoding="utf-8")
        _append_generation(roots, current, version, "applied")
        promotion_started = True
        if roots.previous_pkg_root.exists():
            shutil.move(str(roots.previous_pkg_root), str(older_package))
        if previous_external.exists():
            shutil.move(str(previous_external), str(older_external))
        shutil.move(str(package), str(roots.previous_pkg_root))
        shutil.move(str(external), str(previous_external))
    except BaseException:
        try:
            restore_ledger_after(roots, ledger_before)
            external_image_root = external if external.exists() else previous_external
            if images:
                _restore_external(roots, external_image_root, images)
            if captured_package:
                package_image = package if package.exists() else roots.previous_pkg_root
                shutil.rmtree(roots.pkg_root)
                shutil.copytree(package_image, roots.pkg_root, symlinks=True)
            _write_generations(roots, generations_before)
            if promotion_started:
                if not package.exists() and roots.previous_pkg_root.exists():
                    shutil.rmtree(roots.previous_pkg_root)
                if older_package.exists():
                    shutil.move(str(older_package), str(roots.previous_pkg_root))
                if not external.exists() and previous_external.exists():
                    shutil.rmtree(previous_external)
                if older_external.exists():
                    shutil.move(str(older_external), str(previous_external))
        except BaseException as recovery_error:
            raise LifecycleError("conflict", "Update recovery could not complete; preimages were retained.", {"snapshot": str(snapshot)}) from recovery_error
        shutil.rmtree(snapshot, ignore_errors=True)
        raise
    shutil.rmtree(snapshot)
    result.update({"updated": True, "from": current, "to": version})
    return result


@_serialised(0)
def rollback(roots: Roots, dry_run: bool = False) -> dict[str, Any]:
    from migrations import restore_pre_images

    if not roots.previous_pkg_root.exists() or not roots.pkg_root.exists():
        raise LifecycleError("unavailable", "No previous generation is available to roll back to.")
    external = roots.state / "previous-external"
    receipt = _read_manifest(external / "manifest.json")
    if not receipt:
        raise LifecycleError("unavailable", "Previous generation has no complete external preimages.")
    images = receipt["images"]
    _external_entries(roots, {"data_files": {entry["relative"]: {} for entry in images if entry["group"] == "data"}, "units": [entry["relative"] for entry in images if entry["group"] == "unit"], "bins": [entry["relative"] for entry in images if entry["group"] == "bin"]})
    for entry in images:
        if entry["group"] == "config" and entry["relative"] != "hyprland-settings.lua":
            raise LifecycleError("invalid-data", "Invalid configuration preimage path.")
        if not str(entry["backup"]).isdigit():
            raise LifecycleError("invalid-data", "Invalid external backup identifier.")
        if _external_image(roots, entry["group"], entry["relative"]) != entry["after"]:
            raise LifecycleError("conflict", "An external path changed since update; rollback preserved it.", str(_external_root(roots, entry["group"]) / entry["relative"]))
        if entry["before"]["kind"] == "file" and sha256(external / entry["backup"]) != entry["before"]["sha256"]:
            raise LifecycleError("invalid-data", "External rollback preimage is damaged.")
    if dry_run:
        return {"rolled_back": True, "dry_run": True}
    restored = restore_pre_images(roots)
    salvaged = _salvage_foreign(roots, _operation_stamp())
    _restore_external(roots, external, images)
    shutil.rmtree(roots.pkg_root)
    shutil.copytree(roots.previous_pkg_root, roots.pkg_root, symlinks=True)
    shutil.rmtree(roots.previous_pkg_root)
    shutil.rmtree(external)
    _append_generation(roots, "current", "previous", "rolled-back")
    return {"rolled_back": True, "pre_images_restored": restored, "salvaged": salvaged}


REQUIRED_COMMANDS = ("python3", "quickshell", "jq")


def check_dependencies() -> list[dict[str, Any]]:
    checks: list[dict[str, Any]] = []

    def have(command: str) -> bool:
        return shutil.which(command) is not None

    for command in REQUIRED_COMMANDS:
        present = have(command)
        checks.append({
            "id": f"command-{command}",
            "severity": "info" if present else "error",
            "ok": present,
            "detail": None if present else "required command is missing",
        })
    font_ok = False
    fc_list = shutil.which("fc-list")
    if fc_list:
        completed = subprocess.run([fc_list, ":"], capture_output=True, text=True, check=False)
        font_ok = completed.returncode == 0 and "nerd font propo" in completed.stdout.lower()
    checks.append({
        "id": "font-nerd-propo",
        "severity": "info" if font_ok else "warn",
        "ok": font_ok,
        "detail": None if font_ok else "no Nerd Font Propo family found; bar glyphs will fall back",
    })
    return checks
