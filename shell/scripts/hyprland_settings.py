"""Render and activate the Blox-owned Hyprland settings Lua module.

The Settings owner calls apply with a complete validated candidate. Recovery is
deliberately separate so shell startup can restore an interrupted transaction
once, without trying to reload Hyprland during startup.
"""

from __future__ import annotations

import base64
import copy
import hashlib
import json
import os
import re
import stat
import subprocess
import sys
from pathlib import Path
from typing import Any, Callable, Iterable

try:
    from .settings_document import SettingsDocument
except ImportError:  # Invoked as the shell's recovery script.
    from settings_document import SettingsDocument

MODULE = "hyprland-settings.lua"
JOURNAL = "hyprland-settings.recovery.json"
MARKER = "-- Blox-owned Hyprland Settings module v1\n"
ENTRYPOINT_LINE = 'assert(loadfile((os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")) .. "/blox/hyprland-settings.lua"))()'
SAFE_WORD = re.compile(r"^[A-Za-z0-9_./:@%+=,-]+$")
SAFE_KEY = re.compile(r"^[A-Za-z0-9_:.-]+$")
COMMON = {
    "input.follow_mouse": ("input", "follow_mouse", int, 0, 3),
    "misc.disable_hyprland_logo": ("misc", "disable_hyprland_logo", bool, None, None),
}


class HyprlandSettingsError(RuntimeError):
    pass


class HyprlandSettingsBeforeMutationError(HyprlandSettingsError):
    """The locked revision check refused publication without changing any owner files."""


def _literal(value: str) -> str:
    # JSON's ASCII escapes are accepted by Lua for the restricted ASCII input.
    if not value.isascii() or any(ord(char) < 32 for char in value):
        raise ValueError("control or non-ASCII character in Hyprland value")
    return json.dumps(value)


def load_assertion(receipt: str) -> str:
    """eval acknowledges success; assert verifies the loaded value without changing it."""
    return f'assert(_G.__blox_hyprland_settings == {_literal(receipt)}, "Blox Hyprland module receipt mismatch")'


def _command(argv: list[str]) -> str:
    if not argv or any(not isinstance(word, str) or not SAFE_WORD.fullmatch(word) for word in argv):
        raise ValueError("command arguments must be non-empty plain words")
    return " ".join(argv)


def render(settings: dict[str, Any], common: dict[str, Any] | None = None) -> bytes:
    """Generate calls from schema data; no field may supply Lua source."""
    SettingsDocument()._validate(settings)
    common = common or {}
    if not isinstance(common, dict) or common.keys() - COMMON.keys():
        raise ValueError("unapproved Hyprland setting")
    lines = [MARKER.rstrip(), "-- Generated by Blox. Edit Settings, not this file."]
    if common:
        groups: dict[str, list[str]] = {}
        for key, value in sorted(common.items()):
            group, field, kind, low, high = COMMON[key]
            if type(value) is not kind or (kind is int and not low <= value <= high):
                raise ValueError(f"invalid Hyprland setting: {key}")
            encoded = str(value).lower() if kind is bool else str(value)
            groups.setdefault(group, []).append(f"{field} = {encoded}")
        lines.append("hl.config({ " + ", ".join(f"{group} = {{ {', '.join(fields)} }}" for group, fields in groups.items()) + " })")
    ids: set[str] = set()
    chords: set[str] = set()
    for bind in settings["binds"]:
        if bind["id"] in ids:
            raise ValueError("duplicate bind id")
        ids.add(bind["id"])
        if not bind["enabled"]:
            continue
        if not SAFE_KEY.fullmatch(bind["key"]):
            raise ValueError("unsafe bind key")
        if bind["action"] != "exec":
            raise ValueError("unsupported bind action")
        chord = " + ".join([*bind["modifiers"], bind["key"]])
        if chord in chords:
            raise ValueError("duplicate bind chord")
        chords.add(chord)
        command = _command(bind["arguments"])
        lines.append(f"hl.bind({_literal(chord)}, hl.dsp.exec_cmd({_literal(command)}))")
    ids.clear()
    starts = []
    for item in settings["autostart"]:
        if item["id"] in ids:
            raise ValueError("duplicate autostart id")
        ids.add(item["id"])
        if item["enabled"]:
            starts.append((_command(item["argv"]), item["delaySeconds"]))
    if starts:
        lines.append('hl.on("hyprland.start", function()')
        for command, delay in starts:
            if delay:
                lines.append(f"    hl.timer(function() hl.exec_cmd({_literal(command)}) end, {{ timeout = {delay * 1000}, type = \"once\" }})")
            else:
                lines.append(f"    hl.exec_cmd({_literal(command)})")
        lines.append("end)")
    digest = hashlib.sha256(json.dumps({"settings": settings, "common": common}, sort_keys=True,
                                       separators=(",", ":")).encode()).hexdigest()
    lines.append(f'_G.__blox_hyprland_settings = "{settings["revision"]}:{digest}"')
    return ("\n".join(lines) + "\n").encode("ascii")


def _run(command: list[str], *, input: bytes | None = None) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(command, input=input, capture_output=True, timeout=5, check=False)


class HyprlandSettingsOwner:
    def __init__(self, root: str | Path, runner: Callable[..., subprocess.CompletedProcess[bytes]] = _run):
        self.document = SettingsDocument(root)
        self.runner = runner

    def preflight(self) -> None:
        """Require the fixed include; the product never changes the personal entrypoint."""
        entrypoint = self.document.root / "hypr" / "hyprland.lua"
        try:
            dfd = self.document._dir(False)
        except OSError as error:
            raise HyprlandSettingsError("Blox Hyprland module is unavailable. Install Blox before adding its include") from error
        try:
            module = self._read(dfd, MODULE)
            if module is None:
                raise HyprlandSettingsError("Blox Hyprland module is unavailable. Install Blox before adding its include")
            if not module.startswith(MARKER.encode()):
                raise HyprlandSettingsError("existing Hyprland module is foreign")
        finally:
            os.close(dfd)
        try:
            # Personal dotfiles may be symlinks. Resolve for a read only, then
            # verify the opened leaf rather than granting write ownership.
            fd = os.open(entrypoint.resolve(strict=True), os.O_RDONLY | os.O_NONBLOCK | os.O_NOFOLLOW)
            try:
                info = os.fstat(fd)
                if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid():
                    raise HyprlandSettingsError("Hyprland entrypoint is not an owned regular file")
                with os.fdopen(fd, "rb", closefd=False) as stream:
                    raw = stream.read(1024 * 1024 + 1)
                if len(raw) > 1024 * 1024:
                    raise HyprlandSettingsError("Hyprland entrypoint is too large to verify")
                # Exact executable line avoids accepting a commented/string include.
                text = raw.decode("utf-8")
                ignored = list(re.finditer(r'--\[(=*)\[.*?\]\1\]|--[^\n]*|\[(=*)\[.*?\]\2\]|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'', text, re.S))
                lines = list(re.finditer(r"[^\n]+", text))
                if not any(line.group().strip() == ENTRYPOINT_LINE
                           and not any(token.start() <= line.start() < token.end() for token in ignored)
                           for line in lines):
                    raise HyprlandSettingsError("Blox Hyprland module is unavailable. Add this line to "
                                                + str(entrypoint) + ": " + ENTRYPOINT_LINE)
            finally:
                os.close(fd)
        except (OSError, UnicodeError) as error:
            raise HyprlandSettingsError("Blox Hyprland module is unavailable. Add the fixed include to "
                                        + str(entrypoint) + ": " + ENTRYPOINT_LINE) from error

    @staticmethod
    def _read(dfd: int, name: str) -> bytes | None:
        try:
            fd = os.open(name, os.O_RDONLY | os.O_NONBLOCK | os.O_NOFOLLOW, dir_fd=dfd)
        except FileNotFoundError:
            return None
        try:
            info = os.fstat(fd)
            if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or info.st_nlink != 1 or stat.S_IMODE(info.st_mode) & 0o077:
                raise HyprlandSettingsError(f"unsafe or foreign file: {name}")
            with os.fdopen(fd, "rb", closefd=False) as stream:
                data = stream.read(1024 * 1024 + 1)
            if len(data) > 1024 * 1024:
                raise HyprlandSettingsError(f"oversized file: {name}")
            return data
        finally:
            os.close(fd)

    @staticmethod
    def _publish(dfd: int, name: str, data: bytes | None) -> None:
        if data is None:
            os.unlink(name, dir_fd=dfd)
        else:
            temporary = f".{name}.{os.getpid()}.tmp"
            fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=dfd)
            try:
                with os.fdopen(fd, "wb", closefd=False) as stream:
                    stream.write(data)
                    stream.flush()
                os.fsync(fd)
            finally:
                os.close(fd)
            try:
                os.replace(temporary, name, src_dir_fd=dfd, dst_dir_fd=dfd)
            finally:
                try:
                    os.unlink(temporary, dir_fd=dfd)
                except FileNotFoundError:
                    pass
        os.fsync(dfd)

    def _snapshot(self, dfd: int) -> tuple[bytes | None, bytes | None]:
        module = self._read(dfd, MODULE)
        if module is not None and not module.startswith(MARKER.encode()):
            raise HyprlandSettingsError("existing Hyprland module is foreign")
        return module, self._read(dfd, "settings.json")

    def _recover(self, dfd: int) -> bool:
        raw = self._read(dfd, JOURNAL)
        if raw is None:
            return False
        try:
            journal = json.loads(raw)
            if journal.get("version") not in (1, 2):
                raise ValueError("unknown recovery version")
            module = base64.b64decode(journal["module"], validate=True) if journal["module"] is not None else None
            settings = base64.b64decode(journal["settings"], validate=True) if journal["settings"] is not None else None
            backup = base64.b64decode(journal["backup"], validate=True) if journal["backup"] is not None else None
            if module is not None and not module.startswith(MARKER.encode()):
                raise ValueError("foreign module in recovery record")
            for image in (settings, backup):
                if image is not None:
                    self.document._migrate(json.loads(image))
            current = self._read(dfd, MODULE)
            if current is not None and not current.startswith(MARKER.encode()):
                raise HyprlandSettingsError("foreign module blocks recovery")
            if journal["version"] == 2:
                after = journal["after"]
                originals = {MODULE: module, "settings.json": settings, "settings.json.bak": backup}
                if not isinstance(after, dict) or set(after) != set(originals):
                    raise ValueError("invalid recovery post-image")
                for name, original in originals.items():
                    expected = base64.b64decode(after[name], validate=True) if after[name] is not None else None
                    if self._read(dfd, name) not in (original, expected):
                        raise HyprlandSettingsError("Hyprland recovery would overwrite a newer Settings or module change")
            self._publish(dfd, MODULE, module) if module is not None or current is not None else None
            current_settings = self._read(dfd, "settings.json")
            self._publish(dfd, "settings.json", settings) if settings is not None or current_settings is not None else None
            current_backup = self._read(dfd, "settings.json.bak")
            self._publish(dfd, "settings.json.bak", backup) if backup is not None or current_backup is not None else None
            self._publish(dfd, JOURNAL, None)
            return True
        except (KeyError, ValueError, TypeError) as error:
            raise HyprlandSettingsError("invalid Hyprland recovery record") from error

    def recover_cold_start(self) -> bool:
        """Restore one pending transaction and clear its record; never reload."""
        try:
            dfd = self.document._dir(False)
        except FileNotFoundError:
            return False
        try:
            if self._read(dfd, JOURNAL) is None:
                return False
        finally:
            os.close(dfd)
        with self.document._locked_dir(create=False) as dfd:
            return self._recover(dfd)

    def capture_preimage(self) -> dict[str, str | None]:
        """Return exact validated bytes for a wider Apply transaction."""
        try:
            dfd = self.document._dir(False)
        except FileNotFoundError:
            return {name: None for name in (MODULE, "settings.json", "settings.json.bak")}
        try:
            if self._read(dfd, JOURNAL) is not None:
                raise HyprlandSettingsError("pending Hyprland recovery must run first")
            module, settings = self._snapshot(dfd)
            backup = self._read(dfd, "settings.json.bak")
            for image in (settings, backup):
                if image is not None:
                    self.document._migrate(json.loads(image))
            values = {MODULE: module, "settings.json": settings, "settings.json.bak": backup}
            return {name: base64.b64encode(data).decode() if data is not None else None
                    for name, data in values.items()}
        finally:
            os.close(dfd)

    def restore_preimage(self, image: dict[str, str | None], *,
                         allowed_settings: Iterable[tuple[int, str]] | None = None,
                         allowed_modules: Iterable[str | None] | None = None) -> None:
        """Restore the outer transaction's exact files without a reload loop."""
        if not isinstance(image, dict) or set(image) != {MODULE, "settings.json", "settings.json.bak"}:
            raise HyprlandSettingsError("invalid Apply pre-image")
        try:
            decoded = {name: base64.b64decode(value, validate=True) if value is not None else None
                       for name, value in image.items()}
            if decoded[MODULE] is not None and not decoded[MODULE].startswith(MARKER.encode()):
                raise HyprlandSettingsError("foreign module in Apply pre-image")
            for name in ("settings.json", "settings.json.bak"):
                if decoded[name] is not None:
                    self.document._migrate(json.loads(decoded[name]))
        except (ValueError, TypeError, json.JSONDecodeError) as error:
            raise HyprlandSettingsError("invalid Apply pre-image") from error
        lock = self.document._locked_dir()
        dfd = lock.__enter__()
        try:
            if allowed_settings is not None:
                selected, _ = self.document._select_preimage(dfd)
                payload = (json.dumps(selected, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode()
                identity = (selected["revision"], hashlib.sha256(payload).hexdigest())
                if identity not in set(allowed_settings):
                    raise HyprlandSettingsError("Apply restore would overwrite a newer Settings change")
            if allowed_modules is not None:
                current_module = self._read(dfd, MODULE)
                module_image = base64.b64encode(current_module).decode() if current_module is not None else None
                if module_image not in set(allowed_modules):
                    raise HyprlandSettingsError("Apply restore would overwrite a newer Hyprland module change")
            if self._read(dfd, JOURNAL) is not None:
                self._recover(dfd)
            current = self._read(dfd, MODULE)
            if current is not None and not current.startswith(MARKER.encode()):
                raise HyprlandSettingsError("foreign module blocks Apply restore")
            for name in (MODULE, "settings.json", "settings.json.bak"):
                if decoded[name] is not None or self._read(dfd, name) is not None:
                    self._publish(dfd, name, decoded[name])
            if self.capture_preimage() != image:
                raise HyprlandSettingsError("Apply pre-image restore differs")
        finally:
            lock.__exit__(None, None, None)

    def _verify_loaded(self, source: bytes) -> None:
        marker = re.search(rb'^_G\.__blox_hyprland_settings = "([0-9]+:[0-9a-f]{64})"$', source, re.M)
        if marker is None:
            return  # Previous marked modules predate the execution receipt.
        observed = self.runner(["hyprctl", "eval", load_assertion(marker.group(1).decode("ascii"))])
        if observed.returncode or observed.stdout.strip() != b"ok":
            raise HyprlandSettingsError("Blox Hyprland module was not loaded or its loaded revision differs")

    def reload_restored(self) -> None:
        """Ask Hyprland to load a restored module and check its reported errors."""
        reloaded = self.runner(["hyprctl", "reload"])
        if reloaded.returncode or reloaded.stdout.strip() != b"ok":
            raise HyprlandSettingsError("Hyprland restore reload failed")
        errors = self.runner(["hyprctl", "configerrors"])
        if errors.returncode or errors.stdout.strip() not in (b"", b"no flags were set"):
            raise HyprlandSettingsError("Hyprland reported errors after restore")
        try:
            dfd = self.document._dir(False)
        except FileNotFoundError:
            return
        try:
            source = self._read(dfd, MODULE)
            if source is not None:
                self._verify_loaded(source)
        finally:
            os.close(dfd)


    def apply(self, candidate: dict[str, Any], expected_revision: int,
              common: dict[str, Any] | None = None) -> dict[str, Any]:
        """Commit Settings and the module, then ask Hyprland to reload once."""
        published = copy.deepcopy(candidate)
        published["revision"] = expected_revision + 1
        source = render(published, common)
        self.preflight()
        syntax = self.runner(["luac", "-p", "-"], input=source)
        if syntax.returncode:
            raise HyprlandSettingsError("generated Lua failed syntax validation")
        lock = self.document._locked_dir()
        dfd = lock.__enter__()
        journal_written = False
        try:
            if self._read(dfd, JOURNAL) is not None:
                raise HyprlandSettingsError("pending Hyprland recovery must run first")
            module_before, settings_before = self._snapshot(dfd)
            backup_before = self._read(dfd, "settings.json.bak")
            current = self.document.get()
            if not current.ok or current.revision != expected_revision:
                raise HyprlandSettingsBeforeMutationError("Settings revision changed or is unsafe")
            encoded_after = (json.dumps(published, sort_keys=True, indent=2) + "\n").encode()
            before_data, _ = self.document._select_preimage(dfd)
            encoded_backup = (json.dumps(before_data, sort_keys=True, indent=2) + "\n").encode() if settings_before is not None else backup_before
            record = {"version": 2,
                      "after": {MODULE: base64.b64encode(source).decode(),
                                "settings.json": base64.b64encode(encoded_after).decode(),
                                "settings.json.bak": base64.b64encode(encoded_backup).decode() if encoded_backup is not None else None},
                      "module": base64.b64encode(module_before).decode() if module_before is not None else None,
                      "settings": base64.b64encode(settings_before).decode() if settings_before is not None else None,
                      "backup": base64.b64encode(backup_before).decode() if backup_before is not None else None}
            journal_bytes = json.dumps(record, sort_keys=True).encode()
            if len(journal_bytes) > 1024 * 1024:
                raise HyprlandSettingsError("Hyprland transaction exceeds its recovery record size limit")
            self._publish(dfd, JOURNAL, journal_bytes)
            journal_written = True
            result = self.document._transact(lambda doc: (copy.deepcopy(candidate), ("binds", "autostart")), expected_revision, locked_dfd=dfd)
            if not result.ok:
                raise HyprlandSettingsError(f"Settings commit failed: {result.code}")
            self._publish(dfd, MODULE, source)
            reload_result = self.runner(["hyprctl", "reload"])
            if reload_result.returncode or reload_result.stdout.strip() != b"ok":
                raise HyprlandSettingsError("Hyprland reload failed")
            errors = self.runner(["hyprctl", "configerrors"])
            if errors.returncode or errors.stdout.strip() not in (b"", b"no flags were set"):
                raise HyprlandSettingsError("Hyprland reported configuration errors: " + errors.stdout.decode(errors="replace").strip())
            self._verify_loaded(source)
            self._publish(dfd, JOURNAL, None)
            journal_written = False
            return {"settings": copy.deepcopy(result.data), "module": base64.b64encode(source).decode()}
        except BaseException:
            if journal_written:
                self._recover(dfd)
            raise
        finally:
            lock.__exit__(None, None, None)


def main(argv: list[str] | None = None) -> int:
    arguments = sys.argv[1:] if argv is None else argv
    if arguments != ["recover"]:
        print("usage: hyprland_settings.py recover", file=sys.stderr)
        return 2
    try:
        HyprlandSettingsOwner(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config"))).recover_cold_start()
    except (OSError, ValueError, HyprlandSettingsError) as error:
        print(f"Hyprland Settings recovery failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
