"""Isolated checks for the Blox-owned Hyprland module transaction."""

from __future__ import annotations

import copy
import base64
import re
import threading
import json
import os
import subprocess
import tempfile
import unittest
from pathlib import Path

from shell.scripts.hyprland_settings import (
    ENTRYPOINT_LINE, JOURNAL, MARKER, MODULE, load_assertion, HyprlandSettingsError,
    HyprlandSettingsOwner, HyprlandSettingsBeforeMutationError, render,
)
from themes.lib.blox_theme.composition import component_digest


class HyprlandSettingsTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        entrypoint = self.root / "hypr" / "hyprland.lua"
        entrypoint.parent.mkdir()
        entrypoint.write_text(ENTRYPOINT_LINE + "\n")
        bootstrap = self.root / "blox" / MODULE
        bootstrap.parent.mkdir(mode=0o700)
        self.bootstrap = (MARKER + "-- Generated by Blox. Edit Settings, not this file.\n").encode()
        bootstrap.write_bytes(self.bootstrap)
        bootstrap.chmod(0o600)
        self.calls = []
        self.loaded_marker = None
        self.eval_supported = True
        self.eval_ack = b"ok\n"
        self.fail_reload = False
        self.config_errors = b"no flags were set\n"

        def runner(command, **kwargs):
            self.calls.append(command)
            if command[0] == "luac":
                return subprocess.run(command, input=kwargs["input"], capture_output=True, check=False)
            if command == ["hyprctl", "reload"]:
                return subprocess.CompletedProcess(command, 1 if self.fail_reload else 0,
                                                   b"failed" if self.fail_reload else b"ok\n", b"")
            if command[:2] == ["hyprctl", "eval"]:
                if not self.eval_supported:
                    return subprocess.CompletedProcess(command, 0, b"eval is only supported with the lua config manager", b"")
                source = (self.root / "blox" / MODULE).read_bytes()
                marker = re.search(rb'^_G\.__blox_hyprland_settings = "([^"]+)"$', source, re.M)
                loaded = self.loaded_marker if self.loaded_marker is not None else marker.group(1)
                matched = command[2] == load_assertion(loaded.decode("ascii"))
                return subprocess.CompletedProcess(command, 0 if matched else 7,
                                                   self.eval_ack if matched else b"error: Blox Hyprland module receipt mismatch", b"")
            return subprocess.CompletedProcess(command, 0, self.config_errors, b"")

        self.owner = HyprlandSettingsOwner(self.root, runner)
        self.data = copy.deepcopy(self.owner.document.defaults)

    def _app(self):
        path = self.root / "blox"
        path.mkdir(mode=0o700, exist_ok=True)
        return path

    def test_render_structured_values_and_dormant_monitors(self):
        self.data["binds"] = [{"id": "terminal", "enabled": True, "key": "T", "modifiers": ["SUPER"],
                               "action": "exec", "arguments": ["kitty", "--class", "test"]}]
        self.data["autostart"] = [{"id": "clock", "name": "Clock", "enabled": True,
                                   "argv": ["clock-app"], "delaySeconds": 2}]
        self.data["monitors"] = [{"id": "screen", "enabled": True, "width": 1920, "height": 1080,
                                  "refreshRate": 60, "x": 0, "y": 0, "scale": 1, "transform": 0}]
        source = render(self.data, {"input.follow_mouse": 1, "misc.disable_hyprland_logo": True})
        self.assertTrue(source.startswith(MARKER.encode()))
        self.assertIn(b'hl.bind("SUPER + T", hl.dsp.exec_cmd("kitty --class test"))', source)
        self.assertIn(b'timeout = 2000', source)
        self.assertIn(b'follow_mouse = 1', source)
        self.assertNotIn(b'screen', source)
        self.assertEqual(subprocess.run(["luac", "-p", "-"], input=source).returncode, 0)
        self.assertIn('/blox/hyprland-settings.lua', ENTRYPOINT_LINE)

        self.owner.apply(self.data, 0, {"input.follow_mouse": 1})
        app = self.root / "blox"
        stored = json.loads((app / "settings.json").read_bytes())
        generated = (app / MODULE).read_bytes()
        self.assertEqual(stored["monitors"], self.data["monitors"])
        self.assertTrue(generated.startswith(MARKER.encode()))
        self.assertNotIn(b"screen", generated)
        self.assertNotIn(b"monitor", generated.lower())
        self.assertEqual(subprocess.run(["luac", "-p", "-"], input=generated).returncode, 0)

    def test_unsafe_input_rejected_before_writes(self):
        self.data["binds"] = [{"id": "bad", "enabled": True, "key": "T", "modifiers": ["SUPER"],
                               "action": "exec", "arguments": ["kitty;touch", "/tmp/pwned"]}]
        with self.assertRaises(ValueError):
            self.owner.apply(self.data, 0)
        self.assertEqual((self.root / "blox" / MODULE).read_bytes(), self.bootstrap)
        self.assertFalse((self.root / "blox" / "settings.json").exists())

    def test_foreign_file_rejected_unchanged(self):
        app = self._app()
        foreign = app / MODULE
        foreign.write_bytes(b"-- someone else's module\n")
        foreign.chmod(0o600)
        with self.assertRaisesRegex(HyprlandSettingsError, "foreign"):
            self.owner.apply(self.data, 0)
        self.assertEqual(foreign.read_bytes(), b"-- someone else's module\n")
        self.assertFalse((app / "settings.json").exists())
        self.assertEqual(self.calls, [])

    def test_reload_failure_restores_all_preimages(self):
        app = self._app()
        initial = json.dumps(self.data).encode()
        prior = (MARKER + "-- previous\n").encode()
        for name, contents in (("settings.json", initial), ("settings.json.bak", initial), (MODULE, prior)):
            target = app / name
            target.write_bytes(contents)
            target.chmod(0o600)
        self.fail_reload = True
        with self.assertRaisesRegex(HyprlandSettingsError, "reload failed"):
            self.owner.apply(self.data, 0)
        for name, contents in (("settings.json", initial), ("settings.json.bak", initial), (MODULE, prior)):
            self.assertEqual((app / name).read_bytes(), contents)
        self.assertFalse((app / JOURNAL).exists())
        self.assertEqual(self.calls.count(["hyprctl", "reload"]), 1)
        self.assertNotIn(["hyprctl", "configerrors"], self.calls)

    def test_config_errors_restore_and_cold_start_recovers_once(self):
        app = self._app()
        self.config_errors = b"invalid bind\n"
        with self.assertRaisesRegex(HyprlandSettingsError, "configuration errors"):
            self.owner.apply(self.data, 0)
        self.assertEqual((app / MODULE).read_bytes(), self.bootstrap)
        self.assertFalse((app / "settings.json").exists())
        self.assertEqual(self.calls.count(["hyprctl", "reload"]), 1)
        self.config_errors = b"no flags were set\n"
        self.owner.apply(self.data, 0)
        module = (app / MODULE).read_bytes()
        settings = (app / "settings.json").read_bytes()
        record = {"version": 1, "module": None, "settings": None, "backup": None}
        (app / JOURNAL).write_text(json.dumps(record))
        (app / JOURNAL).chmod(0o600)
        count = self.calls.count(["hyprctl", "reload"])
        self.assertTrue(self.owner.recover_cold_start())
        self.assertFalse(self.owner.recover_cold_start())
        self.assertEqual(self.calls.count(["hyprctl", "reload"]), count)
        self.assertFalse((app / MODULE).exists())
        self.assertFalse((app / "settings.json").exists())
        self.assertTrue(module.startswith(MARKER.encode()))
        self.assertEqual(json.loads(settings)["revision"], 1)

    def test_missing_or_commented_include_is_unavailable_before_mutation(self):
        entrypoint = self.root / "hypr" / "hyprland.lua"
        for text in ("-- " + ENTRYPOINT_LINE, "--[[\n" + ENTRYPOINT_LINE + "\n]]",
                     "local text = [[\n" + ENTRYPOINT_LINE + "\n]]"):
            entrypoint.write_text(text)
            with self.assertRaisesRegex(HyprlandSettingsError, "unavailable.*Add"):
                self.owner.apply(self.data, 0)
            self.assertEqual((self.root / "blox" / MODULE).read_bytes(), self.bootstrap)
            self.assertFalse((self.root / "blox" / "settings.json").exists())
            self.assertEqual(entrypoint.read_text(), text)
        entrypoint.unlink()
        with self.assertRaisesRegex(HyprlandSettingsError, "fixed include"):
            self.owner.apply(self.data, 0)
        self.assertEqual(self.calls, [])

    def test_missing_bootstrap_module_is_unavailable_without_recreating_it(self):
        module = self.root / "blox" / MODULE
        module.unlink()
        with self.assertRaisesRegex(HyprlandSettingsError, "Install Blox before adding"):
            self.owner.apply(self.data, 0)
        self.assertFalse(module.exists())
        self.assertFalse((module.parent / "settings.json").exists())
        self.assertEqual(self.calls, [])

    def test_wrong_or_unsupported_execution_receipt_restores_preimages(self):
        for loaded, supported, ack in ((b"", True, b"ok\n"), (b"0:" + b"a" * 64, True, b"ok\n"),
                                       (None, False, b"ok\n"), (None, True, b"")):
            self.loaded_marker = loaded
            self.eval_supported = supported
            self.eval_ack = ack
            with self.assertRaisesRegex(HyprlandSettingsError, "not loaded"):
                self.owner.apply(self.data, 0)
            app = self.root / "blox"
            self.assertEqual((app / MODULE).read_bytes(), self.bootstrap)
            self.assertFalse((app / "settings.json").exists())
            self.assertFalse((app / JOURNAL).exists())

    def test_settings_change_before_locked_recheck_has_a_no_mutation_error(self):
        original = self.owner.runner
        def runner(command, **kwargs):
            result = original(command, **kwargs)
            if command[0] == "luac":
                edited = self.owner.document.set("bar.layout.position", "bottom", 0)
                self.assertTrue(edited.ok)
            return result
        self.owner.runner = runner
        with self.assertRaises(HyprlandSettingsBeforeMutationError):
            self.owner.apply(self.data, 0)
        self.assertEqual((self.root / "blox" / MODULE).read_bytes(), self.bootstrap)
        self.assertFalse((self.root / "blox" / JOURNAL).exists())
        latest = self.owner.document.get()
        self.assertEqual((latest.revision, latest.data["bar"]["layout"]["position"]), (1, "bottom"))

    def test_failed_reload_cannot_overwrite_an_independent_settings_writer(self):
        original = self.owner.runner
        finished = threading.Event()
        started = threading.Event()
        result = []
        def writer():
            started.set()
            result.append(self.owner.document.set("bar.layout.position", "bottom", 0))
            finished.set()
        thread = threading.Thread(target=writer)
        def runner(command, **kwargs):
            if command == ["hyprctl", "reload"]:
                thread.start()
                self.assertTrue(started.wait(1))
                self.assertFalse(finished.wait(.05), "concurrent Settings write escaped the transaction lock")
                return subprocess.CompletedProcess(command, 1, b"failed", b"")
            return original(command, **kwargs)
        self.owner.runner = runner
        with self.assertRaisesRegex(HyprlandSettingsError, "reload failed"):
            self.owner.apply(self.data, 0)
        thread.join(2)
        self.assertFalse(thread.is_alive())
        self.assertTrue(result[0].ok, result[0])
        current = self.owner.document.get()
        self.assertEqual((current.revision, current.data["bar"]["layout"]["position"]), (1, "bottom"))

    def test_oversized_recovery_record_is_rejected_before_any_publication(self):
        app = self._app()
        previous = MARKER.encode() + b"-- prior module padding\n" * 40000
        self.assertLess(len(previous), 1024 * 1024)
        (app / MODULE).write_bytes(previous)
        (app / MODULE).chmod(0o600)
        with self.assertRaisesRegex(HyprlandSettingsError, "size limit"):
            self.owner.apply(self.data, 0)
        self.assertEqual((app / MODULE).read_bytes(), previous)
        self.assertFalse((app / JOURNAL).exists())
        self.assertFalse((app / "settings.json").exists())

    def test_apply_receipt_is_exact_committed_state_even_after_a_newer_writer(self):
        receipt = self.owner.apply(self.data, 0)
        self.assertEqual(receipt["settings"], self.owner.document.get().data)
        self.assertEqual(base64.b64decode(receipt["module"]), (self.root / "blox" / MODULE).read_bytes())
        self.assertTrue(self.owner.document.set("bar.layout.position", "bottom", 1).ok)
        self.assertEqual(receipt["settings"]["revision"], 1)
        self.assertEqual(self.owner.document.get().revision, 2)
        self.assertNotEqual(receipt["settings"], self.owner.document.get().data)

    def test_guarded_restore_preserves_a_writer_between_outer_check_and_owner_lock(self):
        image = self.owner.capture_preimage()
        receipt = self.owner.apply(self.data, 0)
        allowed = [(receipt["settings"]["revision"], component_digest(receipt["settings"]))]
        self.assertTrue(self.owner.document.set("bar.layout.position", "bottom", 1).ok)
        app = self.root / "blox"
        before = {name: (app / name).read_bytes() for name in (MODULE, "settings.json", "settings.json.bak")}
        with self.assertRaisesRegex(HyprlandSettingsError, "newer Settings"):
            self.owner.restore_preimage(image, allowed_settings=allowed,
                                        allowed_modules=[image[MODULE], receipt["module"]])
        self.assertEqual(before, {name: (app / name).read_bytes() for name in before})

    def test_guarded_restore_refuses_a_changed_marked_module_and_accepts_owned_postimage(self):
        image = self.owner.capture_preimage()
        receipt = self.owner.apply(self.data, 0)
        module = self.root / "blox" / MODULE
        module.write_bytes((MARKER + "-- newer personal module\n").encode())
        allowed = [(receipt["settings"]["revision"], component_digest(receipt["settings"]))]
        settings = (module.parent / "settings.json").read_bytes()
        with self.assertRaisesRegex(HyprlandSettingsError, "newer Hyprland module"):
            self.owner.restore_preimage(image, allowed_settings=allowed,
                                        allowed_modules=[image[MODULE], receipt["module"]])
        self.assertEqual(module.read_bytes(), (MARKER + "-- newer personal module\n").encode())
        self.assertEqual((module.parent / "settings.json").read_bytes(), settings)
        module.write_bytes(base64.b64decode(receipt["module"]))
        self.owner.restore_preimage(image, allowed_settings=allowed,
                                    allowed_modules=[image[MODULE], receipt["module"]])
        self.assertEqual(self.owner.capture_preimage(), image)

    def test_cold_recovery_preserves_a_newer_settings_write(self):
        app = self._app()
        self.owner.apply(self.data, 0)
        before = {name: base64.b64encode((app / name).read_bytes()).decode() if (app / name).exists() else None
                  for name in (MODULE, "settings.json", "settings.json.bak")}
        record = {"version": 2, "module": before[MODULE], "settings": before["settings.json"],
                  "backup": before["settings.json.bak"], "after": before}
        (app / JOURNAL).write_text(json.dumps(record))
        (app / JOURNAL).chmod(0o600)
        self.assertTrue(self.owner.document.set("bar.layout.position", "bottom", 1).ok)
        newest = (app / "settings.json").read_bytes()
        with self.assertRaisesRegex(HyprlandSettingsError, "newer"):
            self.owner.recover_cold_start()
        self.assertEqual((app / "settings.json").read_bytes(), newest)
        self.assertTrue((app / JOURNAL).exists())

    def test_cold_start_command_uses_isolated_root(self):
        app = self._app()
        module = app / MODULE
        module.write_bytes((MARKER + "-- interrupted\n").encode())
        module.chmod(0o600)
        record = {"version": 1, "module": None, "settings": None, "backup": None}
        journal = app / JOURNAL
        journal.write_text(json.dumps(record))
        journal.chmod(0o600)
        env = {**os.environ, "XDG_CONFIG_HOME": str(self.root), "PYTHONDONTWRITEBYTECODE": "1"}
        script = Path(__file__).resolve().parents[1] / "shell/scripts/hyprland_settings.py"
        first = subprocess.run(["python3", str(script), "recover"], env=env, capture_output=True)
        second = subprocess.run(["python3", str(script), "recover"], env=env, capture_output=True)
        self.assertEqual((first.returncode, second.returncode), (0, 0))
        self.assertFalse(module.exists())
        self.assertFalse(journal.exists())


if __name__ == "__main__":
    unittest.main()
