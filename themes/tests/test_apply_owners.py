    def test_reset_one_saved_override_does_not_resurrect_source_key(self):
        from themes.lib.blox_theme.apply_owners import rendering_theme
        from themes.lib.blox_theme.core import load_theme, render_theme
        _, source = load_theme('catppuccin-mocha')
        for target in ('gtk', 'hyprlock'):
            source['overrides'][target] = {'background': '#123456', 'foreground': '#ffffff'}
            self.assertTrue(self.settings.set('targets.' + target + '.overrides',
                {'foreground': '#eeddcc'}, self.settings.get().revision).ok)
        rendered = rendering_theme(source, self.settings.get().data)
        files, _ = render_theme(rendered)
        gtk = files['gtk/gtk-3.0/gtk.css']
        lock = files['hyprlock/theme.conf']
        self.assertIn('@define-color blox_bg ' + source['colours']['background'].lower() + ';', gtk)
        self.assertIn('@define-color blox_fg #eeddcc;', gtk)
        self.assertNotIn('#123456', gtk)
        self.assertIn('$background = rgba(' + source['colours']['background'][1:].lower() + 'cc)', lock)
        self.assertIn('$foreground = rgb(eeddcc)', lock)
        self.assertNotIn('123456', lock)
        self.assertEqual(rendered['overrides']['ansi'], source['overrides']['ansi'])
        self.assertEqual(source['overrides']['gtk']['background'], '#123456')
        self.assertEqual(source['overrides']['hyprlock']['background'], '#123456')

