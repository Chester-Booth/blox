        original_micro = micro.apply
        calls = []

        def fail_after_activation(payload):
            calls.append("btop")
            original_btop(payload)
            raise RuntimeError("injected btop failure")

        def track_micro(payload):
            calls.append("micro")
            return original_micro(payload)

        btop.apply = fail_after_activation
        micro.apply = track_micro
