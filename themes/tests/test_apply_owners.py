    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        environment = mock.patch.dict(os.environ, {
            "XDG_CONFIG_HOME": str(self.root / "config"),
            "XDG_STATE_HOME": str(self.root / "state"),
            "XDG_DATA_HOME": str(self.root / "data"),
            "BLOX_DATA_DIR": str(Path(__file__).resolve().parents[1]),
            "BLOX_SHELL_DIR": str(self.root / "shell"),
        })
        environment.start()
        self.addCleanup(environment.stop)
        for target in (
            "themes.lib.blox_theme.obsidian.OBSIDIAN_THEME_SWITCH_SETTLE_SECONDS",
            "themes.lib.blox_theme.obsidian.OBSIDIAN_PACKAGE_APPLY_SETTLE_SECONDS",
            "themes.lib.blox_theme.runtime_editors.ZED_THEME_WATCH_SETTLE_SECONDS",
        ):
            patcher = mock.patch(target, 0)
            patcher.start()
            self.addCleanup(patcher.stop)
        (self.root / "config").mkdir()
        quickshell_loader = self.root / "shell/shared/Theme.qml"
        quickshell_loader.parent.mkdir(parents=True)
        quickshell_loader.write_text("watchChanges: true\nfunction loadJson() {}\n", encoding="utf-8")
        entrypoint = self.root / "config/hypr/hyprland.lua"
        entrypoint.parent.mkdir()
        entrypoint.write_text(ENTRYPOINT_LINE + "\n")
        module = self.root / "config/blox" / MODULE
        module.parent.mkdir(mode=0o700)
        module.write_text(MARKER + "-- Generated by Blox. Edit Settings, not this file.\n")
        module.chmod(0o600)
        self.settings = SettingsDocument()
        for name in ("btop", "micro"):
            outcome = self.settings.set(f"targets.{name}.enabled", True,
                                        self.settings.get().revision)
            self.assertTrue(outcome.ok, outcome)
        self.commands = []

        def runner(command):
            self.commands.append(command)
            return subprocess.CompletedProcess(command, 0, "", "")

        self.runner = runner
        self.hyprland_commands = []
        self.loaded_hyprland_receipt = b""

        def hyprland_runner(command, **kwargs):
            self.hyprland_commands.append(command)
            if command[1:] == ["reload"]:
                module = self.root / "config/blox" / MODULE
                source = module.read_bytes() if module.is_file() else b""
                marker = re.search(rb'^_G\.__blox_hyprland_settings = "([0-9]+:[0-9a-f]{64})"$', source, re.M)
                self.loaded_hyprland_receipt = marker.group(1) if marker else b""
            if command[1] == "eval":
                matched = command[2] == load_assertion(self.loaded_hyprland_receipt.decode("ascii"))
                return subprocess.CompletedProcess(command, 0 if matched else 7,
                                                   b"ok\n" if matched else b"error: receipt mismatch", b"")
            else:
                output = b"no flags were set\n" if command[-1] == "configerrors" else b"ok\n"
            return subprocess.CompletedProcess(command, 0, output, b"")

        self.hyprland_runner = hyprland_runner

    def test_capture_to_core_revision_conflict_preserves_competing_settings(self):
        coordinator, request = create_apply('catppuccin-mocha', run_command=self.runner,
                                            hyprland_runner=self.hyprland_runner)
        original = coordinator.core.apply
        def competing(payload):
            change = self.settings.set('bar.layout.position', 'right', self.settings.get().revision)
            self.assertTrue(change.ok)
            return original(payload)
        coordinator.core.apply = competing
        result = coordinator.apply(request)
