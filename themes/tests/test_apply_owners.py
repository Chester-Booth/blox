        self.assertTrue(result['journalReleased'])
        self.assertEqual(self.settings.get().data['bar']['layout']['position'], 'right')
        self.assertIsNone(runtime.current_generation())
        self.assertNotIn(['hyprctl', 'reload'], self.hyprland_commands)
        self.assertFalse((coordinator.journal_dir / 'apply.json').exists())

