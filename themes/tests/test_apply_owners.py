        btop.apply = original_btop
        retry = coordinator.retry_failed_targets()
        self.assertEqual(retry["code"], "ok")
        self.assertEqual(calls, ["btop", "micro"])
        self.assertEqual(micro.observe()["digest"], partial["targets"]["micro"]["observedDigest"])
