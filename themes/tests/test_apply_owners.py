    def _exercise_deferred_obsidian_apply(self, newer_selection):
        from themes.lib.blox_theme import obsidian, runtime_loaders
        from themes.lib.blox_theme.core import OBSIDIAN_THEME_DIRECTORY
        vault = self.root / 'vault'
        (vault / '.obsidian').mkdir(parents=True)
        appearance = vault / '.obsidian/appearance.json'
        original = b'{"cssTheme":"Previous theme","baseFontSize":19,"customFont":"Keep me"}\n'
        appearance.write_bytes(original)
        registry = self.root / 'config/obsidian/obsidian.json'
        registry.parent.mkdir()
        registry.write_text(json.dumps({'vaults': {'fixture': {'path': str(vault), 'open': True}}}))
        for name in ('btop', 'micro'):
            self.assertTrue(self.settings.set(f'targets.{name}.enabled', False, self.settings.get().revision).ok)
        self.assertTrue(self.settings.set('targets.obsidian.enabled', True, self.settings.get().revision).ok)
        native = {'theme': 'Previous theme'}
        commands = []
        def process(command, **kwargs):
            commands.append(command)
            if 'theme:set' in command:
                native['theme'] = command[-1][5:]
                reply = 'Switched to: ' + native['theme'] if native['theme'] else 'Switched to default theme'
            else:
                if newer_selection:
                    appearance.write_text('{"cssTheme":"New personal choice","baseFontSize":22,"customFont":"Keep me"}')
                reply = native['theme'] or '(default)'
            kwargs['stdout'].write((reply + '\n').encode())
            kwargs['stdout'].flush()
            child = mock.Mock()
            child.poll.return_value = 0
            return child
        with mock.patch.object(runtime, '_run', self.runner), \
             mock.patch.object(runtime_loaders, '_proc_main_pid', return_value=0), \
             mock.patch.object(obsidian, '_obsidian_is_running', return_value=True), \
             mock.patch.object(obsidian.subprocess, 'Popen', side_effect=process), \
             mock.patch.object(obsidian, '_stop_obsidian_cli'), \
             mock.patch.object(obsidian, 'OBSIDIAN_THEME_SWITCH_SETTLE_SECONDS', 0), \
             mock.patch.object(obsidian, 'OBSIDIAN_PACKAGE_APPLY_SETTLE_SECONDS', 0):
            coordinator, request = create_apply('catppuccin-mocha', run_command=runtime._run,
                                                hyprland_runner=self.hyprland_runner)
            result = coordinator.apply(request)
            package = vault / '.obsidian/themes' / OBSIDIAN_THEME_DIRECTORY
            if newer_selection:
                self.assertTrue(result['observationConflict'])
                self.assertTrue(result['actions']['abandonSuperseded'])
                self.assertFalse(result['actions']['rollBack'])
                self.assertEqual(json.loads(appearance.read_text()),
                    {'cssTheme': 'New personal choice', 'baseFontSize': 22, 'customFont': 'Keep me'})
                self.assertFalse(package.exists())
                self.assertIsNone(runtime.current_generation())
                cold = open_existing_apply(run_command=runtime._run, hyprland_runner=self.hyprland_runner)
                self.assertTrue(cold.status()['actions']['abandonSuperseded'])
                with self.assertRaises(ApplyError):
                    cold.roll_back()
                before = appearance.read_bytes()
                cold.abandon_superseded_partial()
                self.assertEqual(appearance.read_bytes(), before)
            else:
                self.assertEqual(result['targets']['obsidian']['state'], 'success')
                self.assertEqual(json.loads(appearance.read_text()),
                    {'cssTheme': 'Blox generated', 'baseFontSize': 19, 'customFont': 'Keep me'})
                self.assertEqual((package / 'theme.css').read_bytes(), (runtime.current_generation()[0] / 'obsidian/theme.css').read_bytes())
                self.assertEqual(coordinator.roll_back()['code'], 'rolled-back')
                self.assertEqual(appearance.read_bytes(), original)
                self.assertFalse(package.exists())
            self.assertTrue(any(command[-1] == 'theme' for command in commands))

    def test_obsidian_settings_apply_selects_native_theme_and_rolls_back_exact_vault(self):
        from themes.lib.blox_theme.core import OBSIDIAN_THEME_DIRECTORY, OBSIDIAN_THEME_NAME
        vault = self.root / 'vault'
        (vault / '.obsidian').mkdir(parents=True)
        appearance = vault / '.obsidian/appearance.json'
        original = b'{"cssTheme":"Previous theme","baseFontSize":19,"customFont":"Keep me"}\n'
        appearance.write_bytes(original)
        registry = self.root / 'config/obsidian/obsidian.json'
        registry.parent.mkdir()
        registry.write_text(json.dumps({'vaults': {'fixture': {'path': str(vault), 'open': True}}}))
        self.assertTrue(self.settings.set('targets.obsidian.enabled', True, self.settings.get().revision).ok)
        def runner(command):
            self.commands.append(command)
            if command[0] == 'obsidian' and 'theme:set' in command:
                document = json.loads(appearance.read_text())
                document['cssTheme'] = next(value[5:] for value in command if value.startswith('name='))
                appearance.write_text(json.dumps(document))
            return subprocess.CompletedProcess(command, 0, '', '')
        coordinator, request = create_apply('catppuccin-mocha', run_command=runner,
                                            hyprland_runner=self.hyprland_runner)
        result = coordinator.apply(request)
        self.assertEqual(result['targets']['obsidian']['state'], 'success')
        self.assertEqual(json.loads(appearance.read_text())['cssTheme'], OBSIDIAN_THEME_NAME)
        package = vault / '.obsidian/themes' / OBSIDIAN_THEME_DIRECTORY
        current, _ = runtime.current_generation()
        self.assertEqual((package / 'theme.css').read_bytes(), (current / 'obsidian/theme.css').read_bytes())
        self.assertTrue((self.root / 'state/blox/theme/integration/obsidian.json').is_file())
        self.assertTrue(any(command[0] == 'obsidian' and 'theme:set' in command for command in self.commands))
        self.assertEqual(coordinator.roll_back()['code'], 'rolled-back')
        self.assertEqual(appearance.read_bytes(), original)
