    def test_target_core_failure_cannot_restore_over_a_new_settings_edit(self):
        from themes.lib.blox_theme.apply_coordinator import CoreApplyFailure
        coordinator, request = create_apply('catppuccin-mocha', run_command=self.runner,
                                            hyprland_runner=self.hyprland_runner)
        def failed(payload):
            change = self.settings.set('bar.layout.position', 'right', self.settings.get().revision)
            self.assertTrue(change.ok)
