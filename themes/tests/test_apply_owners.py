    def test_foreign_edit_after_core_commit_is_not_recorded_as_owned_postimage(self):
        coordinator, request = create_apply('catppuccin-mocha', run_command=self.runner,
                                            hyprland_runner=self.hyprland_runner)
        original = coordinator.core.hyprland.apply
        def competing(candidate, revision, *args, **kwargs):
            receipt = original(candidate, revision, *args, **kwargs)
            change = self.settings.set('bar.layout.position', 'right', self.settings.get().revision)
            self.assertTrue(change.ok)
            return receipt
        with mock.patch.object(coordinator.core.hyprland, 'apply', side_effect=competing):
            with self.assertRaisesRegex(ApplyError, 'Settings changed since core activation|restore incomplete'):
                coordinator.apply(request)
        self.assertEqual(self.settings.get().data['bar']['layout']['position'], 'right')
        journal = json.loads((coordinator.journal_dir / 'apply.json').read_text())
        self.assertLess(journal['settingsAfterRevision'], self.settings.get().revision)
        journal = json.loads((coordinator.journal_dir / 'apply.json').read_text())
        self.assertEqual(journal['phase'], 'restoring')
        self.assertIn('Settings changed', journal['restoreErrors'][0])
        self.assertEqual(self.hyprland_commands.count(['hyprctl', 'reload']), 1)
        reopened = open_existing_apply(run_command=self.runner, hyprland_runner=self.hyprland_runner)
        with self.assertRaisesRegex(ApplyError, 'Settings changed since core activation'):
            reopened.recover()
        self.assertEqual(self.settings.get().data['bar']['layout']['position'], 'right')

    def test_partial_release_and_rollback_keep_history_bounded(self):
        def generations():
            return {path.name for path in (runtime.state_dir() / 'generations').iterdir()
                    if runtime.GENERATION_PATTERN.fullmatch(path.name)}
        for _ in range(4):
            coordinator, request = create_apply('catppuccin-mocha', run_command=self.runner,
                                                hyprland_runner=self.hyprland_runner)
            coordinator.apply(request)
            coordinator.finish()
        for decision in ('keep', 'abandon', 'rollback'):
            with self.subTest(decision=decision):
                protected = generations()
                coordinator, request = create_apply('catppuccin-mocha', run_command=self.runner,
                                                    hyprland_runner=self.hyprland_runner)
                if decision == 'rollback':
                    self.assertEqual(coordinator.apply(request)['code'], 'ok')
                else:
                    with mock.patch.object(coordinator.owners['btop'], 'apply', side_effect=RuntimeError('target failed')):
                        result = coordinator.apply(request)
                        self.assertEqual(result['code'], 'partial')
                        self.assertEqual(result['targets']['micro']['state'], 'restart')
                        self.assertTrue(result['actions']['keepSuccessfulChanges'])
                self.assertTrue(protected <= generations())
                self.assertGreater(len(generations()), runtime.HISTORY_LIMIT + 1)
                if decision == 'keep':
                    kept = coordinator.keep_successful_changes()
                    self.assertEqual(kept['targets']['micro']['state'], 'restart')
                elif decision == 'abandon':
                    self.settings.set('bar.layout.position', 'right', self.settings.get().revision)
                    coordinator.abandon_superseded_partial()
                else:
                    coordinator.roll_back()
                self.assertEqual(len(generations()), runtime.HISTORY_LIMIT + 1)
                self.assertFalse((coordinator.journal_dir / 'apply.json').exists())

    def test_empty_saved_override_reset_renders_palette_for_gtk_and_hyprlock(self):
        from themes.lib.blox_theme.apply_owners import rendering_theme
        from themes.lib.blox_theme.core import load_theme, render_theme, validate_theme
        _, source = load_theme('catppuccin-mocha')
        source['overrides']['gtk'] = {'background': '#123456'}
        source['overrides']['hyprlock'] = {'background': '#654321'}
        source['gtk']['colour_source'] = 'override'
        original = json.dumps(source, sort_keys=True)
        for target in ('gtk', 'hyprlock'):
            with self.subTest(target=target):
                # Opening the selected theme stages both source dictionaries once.
                for name in ('gtk', 'hyprlock'):
                    self.assertTrue(self.settings.set('targets.' + name + '.overrides',
                        source['overrides'][name], self.settings.get().revision).ok)
                self.assertTrue(self.settings.set('targets.' + target + '.overrides', {},
                    self.settings.get().revision).ok)
                rendered = rendering_theme(source, self.settings.get().data)
                palette_background = source['colours']['background'].lower()
                if target == 'gtk':
                    self.assertEqual(rendered['gtk']['colour_source'], 'theme')
                    self.assertEqual(validate_theme(rendered, check_dependencies=False, targets={'gtk'}).errors, [])
                    files, _ = render_theme(rendered)
                    output = files['gtk/gtk-3.0/gtk.css']
                    self.assertIn('@define-color blox_bg ' + palette_background + ';', output)
                    self.assertNotIn('#123456', output)
                else:
                    files, _ = render_theme(rendered)
                    output = files['hyprlock/theme.conf']
                    self.assertIn('$background = rgba(' + palette_background[1:] + 'cc)', output)
                    self.assertNotIn('654321', output)
                other = 'hyprlock' if target == 'gtk' else 'gtk'
                self.assertEqual(rendered['overrides'][other], source['overrides'][other])
                self.assertEqual(rendered['overrides']['ansi'], source['overrides']['ansi'])
                self.assertEqual(json.dumps(source, sort_keys=True), original)

